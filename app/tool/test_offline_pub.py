import tempfile
import unittest
from pathlib import Path

import offline_pub

SHA = "a" * 64
REV = "5edddef2176e66ddb3c978a2b44d4008fb2b5b8f"


def lock(sha: str = SHA, rev: str = REV, extra: str = "") -> str:
    return f"""# Generated by pub
packages:
  coqui_acp:
    dependency: "direct main"
    description:
      path: "bindings/dart/coqui_acp"
      ref: "{rev}"
      resolved-ref: "{rev}"
      url: "https://github.com/Boriken-Dev/coqui-acp.git"
    source: git
    version: "0.0.0-alpha.0"
  args:
    dependency: "direct main"
    description:
      name: args
      sha256: {sha}
      url: "https://pub.dev"
    source: hosted
    version: "2.7.0"
  flutter:
    dependency: "direct main"
    description: flutter
    source: sdk
    version: "0.0.0"
{extra}sdks:
  dart: ">=3.9.0 <4.0.0"
"""


class EnvTests(unittest.TestCase):
    def test_env_file_is_read_with_comments_quotes_and_process_variables(self):
        text = (
            "# a comment\n"
            "FLUTTER_ROOT=${HOME_DIR}/flutter\n"
            "export PUB_CACHE=\"/pub cache\"  \n"
            "CARGO_HOME='${HOME_DIR}/literal'\n"
            "CANOA_DEPS=/deps # trailing\n"
            "OTHER=ignored\n"
            "not a line\n"
        )
        values = offline_pub.parse_env(text, {"HOME_DIR": "/home"})
        self.assertEqual(values["FLUTTER_ROOT"], "/home/flutter")
        self.assertEqual(values["PUB_CACHE"], "/pub cache")
        self.assertEqual(values["CARGO_HOME"], "${HOME_DIR}/literal")
        self.assertEqual(values["CANOA_DEPS"], "/deps")
        self.assertNotIn("OTHER", values)

    def test_the_process_environment_overrides_the_env_file(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / ".env").write_text("PUB_CACHE=/from_file\nFLUTTER_ROOT=/sdk\n")
            settings = offline_pub.load_settings(root, {"PUB_CACHE": "/from_process", "UNRELATED": "x"})
            self.assertEqual(settings, {"PUB_CACHE": "/from_process", "FLUTTER_ROOT": "/sdk"})
            self.assertEqual(offline_pub.load_settings(root / "none", {}), {})

    def test_settings_reach_the_environment(self):
        environ = {"PATH": "/usr/bin"}
        offline_pub.apply_settings(
            {"FLUTTER_ROOT": "/sdk", "PUB_CACHE": "/pc", "CARGO_HOME": "/cargo"}, environ,
        )
        self.assertEqual(environ["PUB_CACHE"], "/pc")
        self.assertEqual(environ["CARGO_HOME"], "/cargo")
        parts = environ["PATH"].split(offline_pub.os.pathsep)
        self.assertEqual(parts[0], str(Path("/sdk") / "bin"))
        self.assertEqual(parts[1], str(Path("/cargo") / "bin"))
        self.assertEqual(parts[-1], "/usr/bin")


class PlanTests(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        tmp = Path(self._tmp.name)
        self.deps = tmp / "deps"
        self.user_cache = tmp / "user_cache"
        self.target = tmp / "offline_cache"
        (self.deps / "pub" / "hosted" / "pub.dev" / "args-2.7.0").mkdir(parents=True)
        (self.deps / "pub" / "hosted" / "pub.dev" / "args-2.7.0" / "args.dart").write_text("//")
        (self.deps / "pub" / "hosted" / "pub.dev" / ".cache").mkdir()
        (self.deps / "pub" / "hosted" / "pub.dev" / ".cache" / "args-versions.json").write_text("{}")
        (self.deps / "pubspec.lock").write_text(lock())
        (self.user_cache / "git" / f"coqui-acp-{REV}").mkdir(parents=True)
        (self.user_cache / "git" / "cache" / "coqui-acp-1234").mkdir(parents=True)

    def plan(self, app_lock: str):
        return offline_pub.plan_from(app_lock, self.deps, self.user_cache, self.target)

    def test_a_matching_deps_checkout_is_chosen_and_seeds_a_cache(self):
        plan = self.plan(lock())
        self.assertIsNone(plan.reason)
        self.assertEqual(plan.cache, self.target)
        self.assertTrue((self.target / "hosted" / "pub.dev" / "args-2.7.0" / "args.dart").is_file())
        self.assertTrue((self.target / "hosted" / "pub.dev" / ".cache" / "args-versions.json").is_file())
        self.assertTrue((self.target / "git" / f"coqui-acp-{REV}").is_dir())
        self.assertTrue((self.target / "git" / "cache" / "coqui-acp-1234").is_dir())
        self.assertFalse((self.user_cache / "hosted").exists(), "the user's cache is only read")

    def test_a_different_hosted_package_falls_back_and_names_it(self):
        plan = self.plan(lock(sha="b" * 64))
        self.assertIsNone(plan.cache)
        self.assertIn("pubspec.lock", plan.reason)
        self.assertIn("args", plan.reason)

    def test_a_hosted_package_the_mirror_lacks_falls_back(self):
        (self.deps / "pub" / "hosted" / "pub.dev" / "args-2.7.0" / "args.dart").unlink()
        (self.deps / "pub" / "hosted" / "pub.dev" / "args-2.7.0").rmdir()
        plan = self.plan(lock())
        self.assertIsNone(plan.cache)
        self.assertIn("args-2.7.0", plan.reason)

    def test_a_git_dependency_absent_from_the_pub_cache_falls_back(self):
        other = "c" * 40
        plan = self.plan(lock(rev=other))
        self.assertIsNone(plan.cache)
        self.assertIn("coqui_acp", plan.reason)
        self.assertIn(other[:12], plan.reason)
        self.assertFalse(self.target.exists(), "nothing is seeded for a build that goes online")

    def test_no_deps_checkout_falls_back(self):
        plan = offline_pub.plan_from(lock(), None, self.user_cache, self.target)
        self.assertIsNone(plan.cache)
        self.assertIn("deps", plan.reason)

    def test_lock_parsing_reads_hosted_and_git_entries(self):
        packages = {p.name: p for p in offline_pub.parse_lock(lock())}
        self.assertEqual(set(packages), {"coqui_acp", "args", "flutter"})
        self.assertEqual(packages["args"].sha256, SHA)
        self.assertEqual(packages["args"].version, "2.7.0")
        self.assertEqual(packages["coqui_acp"].resolved_ref, REV)
        self.assertEqual(packages["coqui_acp"].repo, "coqui-acp")
        self.assertEqual(packages["flutter"].source, "sdk")


if __name__ == "__main__":
    unittest.main()
