"""MkDocs hook: the documentation site in the brand's names and look.

Enabled by `hooks:` in mkdocs.yml. The brand is `BRAND_FILE`, else `app/brand.json`. The hook sets the site name, draws the
header's logo from the brand's mark (in `accent`, and in `accent_on_dark` on the dark scheme), paints both schemes with the
default look's colours (`docs/assets/look.json`, which `app/test/docs_look_test.dart` keeps current), and gives a brand other
than the default a favicon of its mark.

A page writes the product's names as placeholders, `{{ name }}`, `{{ short_name }}`, `{{ program }}`, `{{ executable }}`,
`{{ config_file }}`, `{{ folder }}`, `{{ home_dir }}`, `{{ env_prefix }}` and `{{ id }}`, rendered from the brand for every brand.
Any other `{{ ... }}` is left as written. In a link's fragment a placeholder renders as a heading's id would, so a link follows
the heading it names.
"""
from __future__ import annotations

import json
import os
import re
from pathlib import Path

from mkdocs.structure.files import File

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_FILE = ROOT / "app" / "brand.json"
LOOK = "assets/look.json"
SVG_FILL = re.compile(r'(<g\b[^>]*\bfill=")#[0-9A-Fa-f]{6}(")')

PLACEHOLDERS = ("name", "short_name", "program", "executable", "config_file", "folder", "home_dir", "env_prefix", "id")
_PLACEHOLDER = re.compile(r"(\{)?\{\{\s*(" + "|".join(PLACEHOLDERS) + r")\s*\}\}(\})?")
_FRAGMENT = re.compile(r"(\]\([^)\s#]*#)((?:[^)\s{]|\{\{[^}]*\}\}|\{)*)(\))")

_brand: dict[str, str] = {}
_names: dict[str, str] = {}
_default = True


def _load() -> tuple[dict, Path]:
    path = Path(os.environ.get("BRAND_FILE") or DEFAULT_FILE).resolve()
    data = json.loads(path.read_text(encoding="utf-8"))
    return data, path


def _names_of(data: dict) -> dict[str, str]:
    """The brand's names, each defaulting from the ones before it the way the brand file's own rules say."""
    name = data["name"]
    program = data.get("program") or re.sub(r"[^a-z0-9-]", "", name.lower())
    return {
        "name": name,
        "short_name": data["short_name"],
        "id": data["id"],
        "executable": data["executable"],
        "env_prefix": data["env_prefix"],
        "program": program,
        "config_file": data.get("config_file") or f"{program}.cfg",
        "folder": data.get("folder") or name,
        "home_dir": data.get("home_dir") or f".{program}",
    }


def _rgba(color: str, alpha: float) -> str:
    return f"rgba({int(color[1:3], 16)}, {int(color[3:5], 16)}, {int(color[5:7], 16)}, {alpha})"


def _scheme(scheme: str, look: dict[str, str]) -> str:
    return f"""[data-md-color-scheme="{scheme}"] {{
  --md-default-bg-color: {look['page']};
  --md-default-bg-color--light: {_rgba(look['page'], 0.7)};
  --md-default-bg-color--lighter: {_rgba(look['page'], 0.3)};
  --md-default-bg-color--lightest: {_rgba(look['page'], 0.12)};
  --md-default-fg-color: {look['text']};
  --md-default-fg-color--light: {look['muted']};
  --md-default-fg-color--lighter: {_rgba(look['muted'], 0.54)};
  --md-default-fg-color--lightest: {look['border']};
  --md-primary-fg-color: {look['bar']};
  --md-primary-fg-color--light: {look['bar']};
  --md-primary-fg-color--dark: {look['bar']};
  --md-primary-bg-color: {look['text']};
  --md-primary-bg-color--light: {look['muted']};
  --md-accent-fg-color: {look['accent']};
  --md-accent-fg-color--transparent: {_rgba(look['accent'], 0.1)};
  --md-accent-bg-color: {look['on_accent']};
  --md-accent-bg-color--light: {look['on_accent']};
  --md-typeset-color: {look['text']};
  --md-typeset-a-color: {look['accent']};
  --md-code-bg-color: {look['surface']};
  --md-code-fg-color: {look['text']};
  --md-footer-bg-color: {look['rail']};
  --md-footer-bg-color--dark: {look['rail']};
  --md-footer-fg-color: {look['text']};
  --md-footer-fg-color--light: {look['muted']};
  --md-footer-fg-color--lighter: {look['muted']};
}}
"""


def _css(look: dict) -> str:
    return (
        "/* Generated by tools/docs_brand.py from the brand and docs/assets/look.json. */\n"
        + _scheme("default", look["light"])
        + _scheme("slate", look["dark"])
        + '[data-md-color-scheme="slate"] .md-header__button.md-logo img { content: url(logo-dark.svg); }\n'
    )


def _logo(icon: Path, name: str, accent: str) -> str:
    svg = icon.read_text(encoding="utf-8")
    svg = SVG_FILL.sub(lambda m: m.group(1) + accent + m.group(2), svg, count=1)
    return re.sub(r"<title>.*?</title>", f"<title>{name}</title>", svg, count=1, flags=re.S)


def on_config(config):
    global _brand, _names, _default
    data, path = _load()
    default_data = json.loads(DEFAULT_FILE.read_text(encoding="utf-8"))
    _brand = {**data, "_icon": str((path.parent / data["icon"]).resolve()), "_path": str(path)}
    _names = _names_of(data)
    _default = data == default_data and (path.parent / data["icon"]).resolve() == (DEFAULT_FILE.parent / default_data["icon"]).resolve()
    config.site_name = data["name"]
    config.theme["logo"] = "assets/logo.svg"
    if not _default:
        config.theme["favicon"] = "assets/favicon.svg"
    config.extra_css = [*config.extra_css, "assets/brand.css"]
    return config


def on_files(files, config):
    look = json.loads((Path(config.docs_dir) / LOOK).read_text(encoding="utf-8"))
    icon = Path(_brand["_icon"])
    accent = _brand["accent"]
    on_dark = _brand.get("accent_on_dark", accent)
    name = _brand["name"]
    generated = {
        "assets/brand.css": _css(look),
        "assets/logo.svg": _logo(icon, name, accent),
        "assets/logo-dark.svg": _logo(icon, name, on_dark),
    }
    if not _default:
        generated["assets/favicon.svg"] = _logo(icon, name, accent)
    for uri, content in generated.items():
        files.append(File.generated(config, uri, content=content))
    # The look's colours are an input of this hook, not a page of the site.
    stale = files.get_file_from_path(LOOK)
    if stale is not None:
        files.remove(stale)
    return files


def _slug(text: str) -> str:
    """The id MkDocs gives a heading holding `text`."""
    return re.sub(r"[-\s]+", "-", re.sub(r"[^\w\s-]", "", text).strip().lower())


def render(markdown: str, names: dict[str, str]) -> str:
    """`markdown` with each placeholder written as the brand's name, and as its id inside a link's fragment.

    Three braces on each side, `{{{ name }}}`, keep the placeholder as written, with two.
    """

    def value(m: re.Match[str], fragment: bool = False) -> str:
        if m.group(1) and m.group(3):
            return m.group(0)[1:-1]
        return _slug(names[m.group(2)]) if fragment else names[m.group(2)]

    markdown = _FRAGMENT.sub(
        lambda m: m.group(1) + _PLACEHOLDER.sub(lambda p: value(p, True), m.group(2)) + m.group(3), markdown
    )
    return _PLACEHOLDER.sub(value, markdown)


def on_page_markdown(markdown, page, config, files):
    return render(markdown, _names)
