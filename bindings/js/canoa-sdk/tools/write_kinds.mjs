// Writes src/kinds.js and src/kinds.d.ts from every canoa.*.kinds.json of crates/canoa/include (a kind two documents both describe is
// written once), or with --check says whether they are current (exit 1 if not). guatiao-kind comes from the Node binding of
// Guatiao: GUATIAO_NODE names its folder (bindings/node/guatiao, built).
import { spawnSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const include = path.resolve(here, '../../../../crates/canoa/include');
const src = path.resolve(here, '../src');
const node = process.env.GUATIAO_NODE;
if (!node) {
  console.error("set GUATIAO_NODE to Guatiao's bindings/node/guatiao folder, built");
  process.exit(2);
}

// The same JSON whatever the order of an object's keys.
const canonical = (value) =>
  JSON.stringify(value, (_key, each) =>
    each && typeof each === 'object' && !Array.isArray(each)
      ? Object.fromEntries(Object.entries(each).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)))
      : each,
  );

const kinds = new Map();
for (const file of readdirSync(include).filter((f) => /^canoa\..*\.kinds\.json$/.test(f)).sort()) {
  for (const kind of JSON.parse(readFileSync(path.join(include, file), 'utf8')).kinds) {
    const known = kinds.get(kind.name);
    if (known && canonical(known) !== canonical(kind)) {
      console.error(`${file}: the kind ${kind.name} differs from another document's`);
      process.exit(2);
    }
    kinds.set(kind.name, kind);
  }
}

// The generator writes where its document is and what it was run with into the first two lines; they name the real inputs here.
const header = (text) => {
  const [, , ...rest] = text.split('\n');
  return [
    '// GENERATED by guatiao-kind from crates/canoa/include/canoa.*.kinds.json. DO NOT EDIT.',
    '// Regenerate: GUATIAO_NODE=<bindings/node/guatiao> node tools/write_kinds.mjs',
    ...rest,
  ].join('\n');
};

const work = mkdtempSync(path.join(tmpdir(), 'canoa-kinds-'));
try {
  writeFileSync(path.join(work, 'canoa.kinds.json'), JSON.stringify({ format: 1, kinds: [...kinds.values()] }, null, 2) + '\n');
  mkdirSync(path.join(work, 'out'));
  const result = spawnSync(
    process.execPath,
    [path.join(node, 'dist/kind_cli.js'), 'canoa.kinds.json', '--out', 'out/kinds'],
    { cwd: work, stdio: 'inherit' },
  );
  if (result.status !== 0) process.exit(result.status ?? 1);
  let current = true;
  for (const name of ['kinds.js', 'kinds.d.ts']) {
    const text = header(readFileSync(path.join(work, 'out', name), 'utf8'));
    const target = path.join(src, name);
    if (process.argv.includes('--check')) {
      let held = null;
      try {
        held = readFileSync(target, 'utf8');
      } catch {
        // missing counts as not current
      }
      if (held !== text) {
        console.error(`${name} is not what the descriptions write: regenerate it`);
        current = false;
      }
    } else {
      writeFileSync(target, text);
    }
  }
  process.exitCode = current ? 0 : 1;
} finally {
  rmSync(work, { recursive: true, force: true });
}
